// Generates packages/antwars-seat/lib/codec.generated.mjs from the server's own map decoders.
// The seat package is installed alone and cannot import src/, so the generated copy is committed;
// packages/antwars-seat/test/codec.test.mjs fails when it is stale.
// Regenerate: npm run seat-codec
import { readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { fileURLToPath } from "node:url";
import { MAX_BOARD_SIDE_TILES } from "../src/sim/mapBoard.ts";

const ROOT = new URL("../", import.meta.url);
export const SEAT_CODEC_PATH = fileURLToPath(new URL("packages/antwars-seat/lib/codec.generated.mjs", ROOT));

/** Server source files and the top-level functions taken from each, in output order. */
const SOURCES: readonly { file: string; functions: readonly string[] }[] = [
  { file: "src/sim/view.ts", functions: ["expandCells"] },
  { file: "src/mcp/territory.ts", functions: ["tileCount", "unpackTerritory"] },
  { file: "src/mcp/markTable.ts", functions: ["unpackMarks"] },
];

/** One top-level function, from its `function` line to the closing brace at column 0. */
function extractFunction(source: string, file: string, name: string): string {
  const start = new RegExp(`^(export )?function ${name}\\(`, "m").exec(source);
  if (!start) throw new Error(`${file}: top-level function ${name} not found`);
  const end = source.indexOf("\n}", start.index);
  if (end < 0) throw new Error(`${file}: end of function ${name} not found`);
  return source.slice(start.index, end + 2);
}

/** Strip types, then close each whitespace span the stripper blanked: none before ; ) , ] or after (, else one space. */
function stripTypes(typescript: string): string {
  const stripped = stripTypeScriptTypes(typescript, { mode: "strip" });
  if (stripped.length !== typescript.length) throw new Error("Type stripping did not preserve positions");
  let out = "";
  for (let i = 0; i < stripped.length;) {
    if (!/\s/.test(stripped[i]!)) { out += stripped[i++]; continue; }
    let j = i, blanked = false;
    while (j < stripped.length && /\s/.test(stripped[j]!)) { if (!/\s/.test(typescript[j]!)) blanked = true; j++; }
    const span = stripped.slice(i, j);
    out += !blanked || span.includes("\n") ? span : /[;),\]]/.test(stripped[j] ?? "") || out.endsWith("(") ? "" : " ";
    i = j;
  }
  return out;
}

export function renderSeatCodec(): string {
  const parts = SOURCES.flatMap(({ file, functions }) => {
    const source = readFileSync(new URL(file, ROOT), "utf8");
    return functions.map(name => stripTypes(extractFunction(source, file, name)));
  });
  return [
    "// GENERATED by scripts/generate-seat-codec.ts (npm run seat-codec). Do not edit.",
    "// Type-stripped copies of the server's reference decoders:",
    ...SOURCES.map(({ file, functions }) => `//   ${functions.join(", ")}  ${file}`),
    "// Conformance fixtures every implementation should pass: test/fixtures/seat-codec/conformance.json",
    "",
    `const MAX_BOARD_SIDE_TILES = ${MAX_BOARD_SIDE_TILES};`,
    "",
    parts.join("\n\n"),
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(SEAT_CODEC_PATH, renderSeatCodec());
  console.log(`wrote ${SEAT_CODEC_PATH}`);
}
