/** Writer upgrades do not change match rules or previously emitted queen-founding bytes. */
import { createHash } from "node:crypto";
import { readFileSync, rmSync } from "node:fs";
import { startServer } from "../../src/server.ts";
import { logLines, matchLogs, tempDir } from "../server/helpers.ts";
import { describe, expect, it } from "vitest";
import { headerLine, replay, stateHash } from "../../src/sim/log.ts";
import { HISTORICAL_CONFIG } from "../sim/fixtures.ts";
import { decodeMessage, encodeMessage, GRID_SCALE_STREAM_VERSION, streamQueens } from "../../src/live/format.ts";
import { SpectatorState } from "../../src/live/model.ts";
import { playScripted, recordLog } from "../../src/live/record.ts";
import { packMessages, unpackMessages } from "../../src/live/snapshot.ts";
import { PUBLIC_CONFIG } from "../../src/sim/config.ts";

import { playable } from "../playable.ts";

const sha256 = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");

describe("recording writer compatibility", () => {
  it("keeps queen-founding rules output byte-for-byte identical to the pinned writer output", () => {
    // This pin belongs to the pre-terrain queen-founding rules, not today's public map pool.
    // Every match plays at grid scale 2, so the pin is this
    // writer's grid-scale-2 output. The reference-grid pin from main 7690c1563aa462b8bf4438b09ff008a49f11e94a's writer
    // was 106825 bytes, fc9053014935e5d33aa889d04fffc307db7261189b83de668ce15ae650718c30.
    const config = playable({ ...PUBLIC_CONFIG, terrain: undefined, matchTicks: 200 });
    const { lines } = playScripted({ seed: 17, config, agents: 2, ticks: 200 });
    const bytes = packMessages(recordLog(lines));
    expect(bytes.length).toBe(120524);
    expect(sha256(bytes)).toBe("3fb804b864ec578c0c914124bf3e86be674e87313ca43008931fa05c1b299631");
  });

  it("every new header and ordinary live/scripted recording names ant115", () => {
    expect(JSON.parse(headerLine(141, playable({ ...HISTORICAL_CONFIG, matchTicks: 1 }))).holdBehaviour).toBe("ant115");
    const { lines } = playScripted({ seed: 141, config: playable(HISTORICAL_CONFIG), agents: 0, ticks: 1 });
    expect(JSON.parse(lines[0]!).holdBehaviour).toBe("ant115");
  });

  it("the actual server writes ant115 on every newly started ordinary live log", async () => {
    const dataDir = tempDir();
    const server = await startServer({ port: 0, host: "127.0.0.1", dataDir, match: "held",
      simConfig: playable({ ...HISTORICAL_CONFIG, matchTicks: 2 }), seed: 141 });
    try {
      server.startMatch();
      const paths = [...matchLogs(dataDir).values()];
      expect(paths).toHaveLength(1);
      expect(JSON.parse(logLines(paths[0]!)[0]!).holdBehaviour).toBe("ant115");
    } finally { await server.close(); rmSync(dataDir, { recursive: true, force: true }); }
  });

  // The landed writer's byte pin and the v4 file both carry setups without grid scale; neither plays or decodes
  // any longer. The unchanged file is still refused at its setup, never read as another grid scale.
  it("refuses the unchanged v4 file at its setup", () => {
    // First eleven messages of the original shipped excerpt; never regenerated by this test.
    const bytes = readFileSync(new URL("fixtures/historical-v4.bin", import.meta.url));
    expect(sha256(bytes)).toBe("83d6b17303f5bf1fa5309e1bef7ecadf9457c3b35c90529ebef85e0d366bc8b4");
    const packed = unpackMessages(bytes);
    expect(packed).toHaveLength(11);
    expect(packed.every((m) => m[2] === 4)).toBe(true);
    expect(() => decodeMessage(packed[0]!)).toThrow("stream setup version 4 carries no grid scale");
  });

  // Existing recordings decode and replay unchanged, judged against
  // recordings that still decode on the synced base; streams the grid-scale-2 reader refuses stay refused, as the v4 test above shows.
  // Each file is this writer's recordLog(lines, 8), frozen at 06c6e13f before set_brood took
  // call index 7, for rulesConfig("redesign") at grid scale 2 (rules 27) and the same without rules27 (rules 26), seed 17.
  // Its log: tick 0 joins a, b and a again (refused); 1 a observes, b rejoins; 2 a orders go_to 10,10; 3 b marks HELP;
  // 4 b founds a queen at 5,5; 5 b count-marks DEFEND 2; 6 a orders hold. That is all seven earlier call kinds,
  // accepted and refused. Each message's version
  // is the one the base's feature-based selection (src/live/format.ts:847 at 0f902d99 and 06c6e13f) chose for it.
  it.each([
    [27, "e03d69236e8297cd4a281296dd4985fb002a4c2c6ac344dc33ca330dec566d6d", "a2408439de04338bb98c21c7c5a9e66c6728225fd98d6ebc116607c76fd2f0d1"],
    [26, "2e0386c2aef2c716ef66e722de25e29e2ba1168f83c9ca56f0f71328d868bc35", "c8a13e915a1aa3b00011f7425d4e6ceee1c115685f90659dfa93324b05023e84"],
  ])("decodes and replays the frozen rules-%i recording of all seven call kinds unchanged", (rules, fileSha, replaySha) => {
    const bytes = readFileSync(new URL(`fixtures/calls-rules${rules}-06c6e13f.bin`, import.meta.url));
    expect(sha256(bytes)).toBe(fileSha);
    const packed = unpackMessages(bytes);
    expect(packed.map((m) => m[2])).toEqual([GRID_SCALE_STREAM_VERSION, 4, 4, 4, 4, 5, 13, 4, 4]);
    const messages = packed.map(decodeMessage);
    for (const [i, message] of messages.entries()) expect(encodeMessage(message)).toEqual(Uint8Array.from(packed[i]!));
    expect(messages[0]!.full!.setup.gridScale).toBe(2);
    expect(messages.flatMap((m) => m.events.flatMap((e) => e.kind === "call" ? [[m.tick, e.agent, e.call, e.accepted]] : []))).toEqual([
      [1, 0, "join", true], [1, 1, "join", true], [1, 0, "join", false], [2, 0, "observe", true], [2, 1, "rejoin", true],
      [3, 0, "order", true], [4, 1, "mark", false], [5, 1, "found_queen", false], [6, 1, "count_mark", true], [7, 0, "order", false],
    ]);
    const first = messages[0]!;
    const state = new SpectatorState(first.full!, first.tick, first.ants);
    for (const m of messages.slice(1)) state.apply(m);
    expect(state.full.agents.map((a) => [a.joinTick, a.prevCallTick, a.lastCallTick, a.lastCommandTick])).toEqual([[0, 2, 6, 2], [0, 4, 5, 5]]);
    expect(sha256(encodeMessage(state.message()))).toBe(replaySha);
  });

  it("writes historical hatch totals through births and reconnect without changing the simulation", () => {
    const config = { ...HISTORICAL_CONFIG, matchTicks: 200 };
    const { lines, state: truth } = playScripted({ seed: 17, config: playable(config), agents: 2, ticks: 200 });
    const bytes = recordLog(lines), messages = bytes.map(decodeMessage), first = messages[0]!;
    expect(config.queenFounding).toBeUndefined();
    expect(bytes[0]![2]).toBe(GRID_SCALE_STREAM_VERSION);
    expect(first.full!.hatched).toEqual([0, 0]);
    const state = new SpectatorState(first.full!, first.tick, first.ants);
    for (const m of messages.slice(1)) state.apply(m);
    expect(truth.stats.hatched.some((n) => n > 0)).toBe(true);
    expect(state.full.hatched).toEqual(truth.stats.hatched);
    const reconnect = decodeMessage(encodeMessage(state.message()));
    expect(reconnect.full!.hatched).toEqual(truth.stats.hatched);
    expect(streamQueens(reconnect.full!)).toHaveLength(2);
    expect(stateHash(replay(lines, Infinity))).toBe(stateHash(truth));
  });

  it("keeps historical colony overrun progress in its named v5 queen and reconnect", () => {
    const { lines } = playScripted({ seed: 17, config: playable(HISTORICAL_CONFIG), agents: 0, ticks: 1 });
    const first = decodeMessage(recordLog(lines, 0)[0]!);
    const state = new SpectatorState(first.full!, first.tick, first.ants);
    state.apply(decodeMessage(encodeMessage({ tick: 1, full: null, ants: first.ants, events: [{ kind: "overrun", colony: 0, progress: 453, required: 600 }] })));
    expect(state.full.overrun).toEqual([453, 0]);
    expect(streamQueens(state.full)[0]!.overrun).toBe(453);
    expect(streamQueens(decodeMessage(encodeMessage(state.message())).full!)[0]!.overrun).toBe(453);
    state.apply({ tick: 2, ants: first.ants, events: [{ kind: "overrun", colony: 0, progress: 0, required: 600 }] });
    expect(streamQueens(state.full)[0]!.overrun).toBe(0);
  });
});
